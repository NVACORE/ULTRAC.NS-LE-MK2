                <div class="slide-content-text">
                    Discovering abandoned spaces and documenting their decay. There's something hauntingly beautiful about places once filled with human activity now reclaimed by time and nature. I'm drawn to the unique lighting conditions these locations offer—natural light streaming through broken windows creating dramatic shadows and highlighting textures that can't be replicated in studio settings.
