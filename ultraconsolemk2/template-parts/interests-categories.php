    <div class="category-header">
        <span class="category-icon">⚡</span>
        <h2 class="category-title">DIGITAL AESTHETIC</h2>
    </div>

    <div class="full-slides-container">
        <!-- Slide 1 -->
        <div class="full-slide" data-index="0" style="display: block;">
            <div class="full-slide-content">
                <h3 class="slide-title">Glitch Art</h3>
                <div class="slide-content-text">
                    Deliberate corruption of digital data to create unexpected visual effects. I'm particularly drawn to databending techniques that apply audio effects to image data and pixel sorting algorithms that rearrange pixels based on brightness values. These processes reveal the underlying structure of digital images while creating beautiful chaos that mirrors the imperfections in natural systems.
                </div>
            </div>
        </div>

        <!-- Slide 2 -->
        <div class="full-slide" data-index="1" style="display: none;">
            <div class="full-slide-content">
                <h3 class="slide-title">Retro Computing</h3>
                <div class="slide-content-text">
                    Aesthetic of early computer systems, terminals, and interfaces. The constraints of early computing hardware created a distinct visual language—monochrome displays, pixelated graphics, and text-mode interfaces. I find beauty in these limitations and incorporate them into my work, particularly the amber and green phosphor monitor aesthetics and the precise pixel arrangements of early bitmap graphics.
                </div>
            </div>
        </div>

        <!-- Slide 3 -->
        <div class="full-slide" data-index="2" style="display: none;">
            <div class="full-slide-content">
                <h3 class="slide-title">Demoscene</h3>
                <div class="slide-content-text">
                    Computer art subculture focused on producing demos with visual effects. The demoscene's ethos of pushing hardware limitations to create impressive audiovisual experiences resonates with my approach to digital art. I'm inspired by how demoscene artists worked within strict technical constraints to create fluid animations and complex visual effects that seemed impossible on their target hardware.
                </div>
            </div>
        </div>

        <!-- Slide 4 -->
        <div class="full-slide" data-index="3" style="display: none;">
            <div class="full-slide-content">
                <h3 class="slide-title">Vaporwave</h3>
                <div class="slide-content-text">
                    Nostalgic aesthetic with early internet imagery and 80s/90s references. Beyond the stereotypical elements, I'm interested in vaporwave's critical examination of consumer culture and digital capitalism. The juxtaposition of corporate imagery with surreal digital spaces creates a dreamlike quality that influences my approach to composition, especially in how I use color gradients and spatial distortion.
                </div>
            </div>
        </div>
    </div>

